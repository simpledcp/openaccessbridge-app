package firewall

import (
	"strings"

	"github.com/simpledcp/openaccessbridge/internal/model"
)

// Defaults for the parts of the ruleset that are not per-auditorium configuration.
// They are the values §9.1's "common to both variants" block names, plus the
// recorded ACSP defaults (DECISIONS D6/D7).
const (
	// DefaultWebRTCPortRange is the patron-side UDP media range (§9.1 $WEBRTC_RANGE).
	DefaultWebRTCPortRange = "10000-20000"
	// DefaultACSPPort is the PROVISIONAL ACSP port (D7); Phase 0A confirms it (B1).
	DefaultACSPPort = 4170
)

// DefaultPatronWebPorts returns the patron web UI ports opened on the client
// interface (§9.1: `tcp dport { 80, 443 }`).
func DefaultPatronWebPorts() []int { return []int{80, 443} }

// Inputs is the stored configuration a ruleset is derived from. It is deliberately
// plain data rather than a config.Store handle: this package must stay free of the
// SQLite store so the privileged helper (§3.5) links nothing it does not need.
type Inputs struct {
	// Profile is the active deployment/firewall profile (§9.2).
	Profile model.FirewallProfile
	// TheaterIface / ClientIface are the two never-joined zone interfaces (§9.1).
	TheaterIface string
	ClientIface  string
	// Auditorium carries the theater-side facts: the cinema-server allowlist, the
	// ACSP port, and the confirmed initiation direction (§10.5).
	Auditorium model.AuditoriumProfile
	// LocalACSPPort is OpenAccessBridge's own ACSP listener port, used only by
	// Variant B. Zero falls back to the auditorium's ACSPPort.
	LocalACSPPort int
	// AdminOnClientIface requests the admin/setup rule on the client interface. It
	// is honored only where the profile permits it (§8.4) — Generate re-checks.
	AdminOnClientIface bool
	// AdminPort overrides DefaultAdminPort when non-zero.
	AdminPort int
	// WebRTCPortRange overrides DefaultWebRTCPortRange when non-empty.
	WebRTCPortRange string
	// PatronWebPorts overrides DefaultPatronWebPorts when non-empty.
	PatronWebPorts []int
	// SupportEgress is the §9.4 support window, present only while a session is
	// open. It is an INPUT rather than something derived from configuration
	// because it is not configuration: the endpoint is configured, the window is
	// a live state with a deadline on it.
	SupportEgress *SupportEgress
}

// ConfigFromInputs turns stored configuration into a ruleset Config (§9.1: "The
// real ruleset is profile-driven and generated by the firewall manager"). It is
// the single place persisted settings become a firewall posture, so the setup
// wizard, boot, and the runtime re-apply cannot derive different rulesets.
//
// It only fills in defaults; it does not validate. Generate validates and is the
// one that refuses to emit a useless or hole-punching rule.
func ConfigFromInputs(in Inputs) Config {
	aud := in.Auditorium

	acspPort := aud.ACSPPort
	if acspPort == 0 {
		acspPort = DefaultACSPPort // D7: PROVISIONAL default, configurable
	}
	localPort := in.LocalACSPPort
	if localPort == 0 {
		localPort = acspPort
	}
	initiation := aud.ACSPInitiation
	if initiation == "" {
		initiation = model.ACSInitiated // D6: Variant A is the working assumption
	}
	webrtc := in.WebRTCPortRange
	if webrtc == "" {
		webrtc = DefaultWebRTCPortRange
	}
	ports := in.PatronWebPorts
	if len(ports) == 0 {
		ports = DefaultPatronWebPorts()
	}

	return Config{
		Profile:       in.Profile,
		TheaterIface:  in.TheaterIface,
		ClientIface:   in.ClientIface,
		SupportEgress: in.SupportEgress,
		// The stored field is scalar; ParseAllowlist lets an operator express a
		// multi-host allowlist (ACSP endpoint + media block, or a redundant server)
		// without a schema change (§9.1 "IP(s)").
		CinemaServerIPs:    ParseAllowlist(aud.CinemaServerIP),
		ACSPPort:           acspPort,
		LocalACSPPort:      localPort,
		Initiation:         initiation,
		WebRTCPortRange:    webrtc,
		PatronWebPorts:     ports,
		AdminOnClientIface: in.AdminOnClientIface,
		AdminPort:          in.AdminPort,
	}
}

// ParseAllowlist splits a stored allowlist string into entries. Entries may be
// separated by commas, whitespace, or both, so a single stored field can carry
// the several server/IMB IPs §9.1 allows. Empty fragments are dropped; the
// entries are NOT validated here (Generate rejects anything that is not an IP).
func ParseAllowlist(s string) []string {
	fields := strings.FieldsFunc(s, func(r rune) bool {
		return r == ',' || r == ';' || r == ' ' || r == '\t' || r == '\n' || r == '\r'
	})
	out := make([]string, 0, len(fields))
	seen := make(map[string]bool)
	for _, f := range fields {
		if f == "" || seen[f] {
			continue
		}
		seen[f] = true
		out = append(out, f)
	}
	if len(out) == 0 {
		return nil
	}
	return out
}
